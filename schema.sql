-- Seven Elements% public leaderboard schema for Supabase
-- Run this in Supabase > SQL Editor.
create table if not exists public.runs (
  id bigint generated by default as identity primary key,
  runner text not null check (char_length(runner) between 1 and 30),
  seconds integer not null check (seconds > 0 and seconds < 604800),
  version text not null,
  seed text,
  proof text not null,
  notes text,
  status text not null default 'pending' check (status in ('pending','verified','rejected')),
  created_at timestamptz not null default now()
);

alter table public.runs enable row level security;

-- Everyone can view only verified runs publicly.
create policy "Public can view verified runs"
on public.runs for select
to anon, authenticated
using (status = 'verified');

-- Anyone can submit a pending run. Never allow clients to submit as verified.
create policy "Anyone can submit pending runs"
on public.runs for insert
to anon, authenticated
with check (status = 'pending');

-- Do not create public update/delete policies. Verify or reject runs through Supabase dashboard
-- while signed in as project owner, or build a separate authenticated moderator panel.
grant select, insert on public.runs to anon, authenticated;
grant usage, select on sequence public.runs_id_seq to anon, authenticated;
